// Business Quest question bank: keeps the markscheme out of the public repository.
//
// The full bank (questions + markscheme + model answers) is
// src/subjects/business/bank.json. That file is NOT committed (.gitignore).
// What is committed:
//   src/subjects/business/questions.js  the questions only, for the site
//   marker/bank.enc                     the full bank, AES-256-GCM encrypted;
//                                       the marking job decrypts it with the
//                                       BQ_BANK_KEY secret
//
//   node tools/bank.mjs key      print a new random key (base64, 32 bytes)
//   node tools/bank.mjs build    bank.json -> questions.js + marker/bank.enc
//   node tools/bank.mjs decrypt  marker/bank.enc -> bank.json (to edit it)
//   node tools/bank.mjs check    questions.js matches bank.enc (needs the key)
//
// The key comes from the BQ_BANK_KEY environment variable or the file
// .bank-key in the repository root (also not committed).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes, createCipheriv, createDecipheriv } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PLAIN = join(root, 'src/subjects/business/bank.json');
const PUBLIC = join(root, 'src/subjects/business/questions.js');
const ENC = join(root, 'marker/bank.enc');

export function bankKey() {
  let k = process.env.BQ_BANK_KEY || '';
  if (!k && existsSync(join(root, '.bank-key'))) k = readFileSync(join(root, '.bank-key'), 'utf8');
  k = k.trim();
  if (!k) throw new Error('No bank key: set BQ_BANK_KEY or create .bank-key');
  const buf = Buffer.from(k, 'base64');
  if (buf.length !== 32) throw new Error('The bank key must be 32 bytes, base64');
  return buf;
}

export function encrypt(text, key) {
  const iv = randomBytes(12);
  const c = createCipheriv('aes-256-gcm', key, iv);
  const data = Buffer.concat([c.update(text, 'utf8'), c.final()]);
  return JSON.stringify({ v: 1, alg: 'aes-256-gcm', iv: iv.toString('base64'), tag: c.getAuthTag().toString('base64'), data: data.toString('base64') }) + '\n';
}

export function decrypt(blob, key) {
  const o = JSON.parse(blob);
  const d = createDecipheriv('aes-256-gcm', key, Buffer.from(o.iv, 'base64'));
  d.setAuthTag(Buffer.from(o.tag, 'base64'));
  return Buffer.concat([d.update(Buffer.from(o.data, 'base64')), d.final()]).toString('utf8');
}

/** The full bank as an array (decrypts marker/bank.enc). */
export function loadBank(key) {
  return JSON.parse(decrypt(readFileSync(ENC, 'utf8'), key || bankKey()));
}

/** What the site may show before marking: no markscheme, model answer or notes. */
export function publicPart(bank) {
  return bank.map((q) => ({ n: q.n, sub: q.sub, marks: q.marks, ct: q.ct, ao: q.ao, hl: !!q.hl, q: q.q, any: q.any || null }));
}

export function publicJs(bank) {
  return '/* Business Quest: IB Business Management Unit 1 questions (generated by tools/bank.mjs build;\n' +
    ' * markscheme and model answers are kept out of the site, see README). */\n' +
    'window.BQ_QUESTIONS = ' + JSON.stringify(publicPart(bank), null, 0).replace(/\},\{"n"/g, '},\n{"n"') + ';\n';
}

function validate(bank) {
  if (!Array.isArray(bank) || bank.length === 0) throw new Error('bank.json must be a non-empty array');
  const seen = new Set();
  for (const q of bank) {
    for (const k of ['n', 'sub', 'marks', 'ct', 'ao', 'q', 'ms', 'pts']) if (q[k] === undefined) throw new Error(`Q${q.n}: missing ${k}`);
    if (seen.has(q.n)) throw new Error(`Q${q.n} twice`);
    seen.add(q.n);
    if (!Array.isArray(q.q) || !Array.isArray(q.pts)) throw new Error(`Q${q.n}: q and pts must be arrays`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const cmd = process.argv[2];
  if (cmd === 'key') {
    console.log(randomBytes(32).toString('base64'));
  } else if (cmd === 'build') {
    const text = readFileSync(PLAIN, 'utf8');
    const bank = JSON.parse(text);
    validate(bank);
    writeFileSync(PUBLIC, publicJs(bank));
    writeFileSync(ENC, encrypt(JSON.stringify(bank), bankKey()));
    console.log(`${bank.length} questions, ${bank.reduce((s, q) => s + q.marks, 0)} marks -> questions.js + marker/bank.enc`);
  } else if (cmd === 'decrypt') {
    writeFileSync(PLAIN, JSON.stringify(loadBank(), null, 1) + '\n');
    console.log('Wrote ' + PLAIN);
  } else if (cmd === 'check') {
    const bank = loadBank();
    validate(bank);
    if (readFileSync(PUBLIC, 'utf8') !== publicJs(bank)) throw new Error('questions.js is out of date: run node tools/bank.mjs build');
    console.log(`OK: bank.enc decrypts (${bank.length} questions) and matches questions.js`);
  } else {
    console.log('Usage: node tools/bank.mjs key|build|decrypt|check');
    process.exit(1);
  }
}
